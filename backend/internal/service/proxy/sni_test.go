package proxy

import (
	"testing"
)

func TestExtractSNI(t *testing.T) {
	// A raw TLS Client Hello frame containing SNI "example.com"
	rawClientHello := []byte{
		0x16, 0x03, 0x01, 0x00, 0x4a, 0x01, 0x00, 0x00, 0x46, 0x03, 0x03, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
		0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x01, 0x00, 0x00, 0x1d, 0x00, 0x00, 0x00, 0x10, 0x00,
		0x0e, 0x00, 0x00, 0x0b, 0x65, 0x78, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x2e, 0x63, 0x6f, 0x6d,
	}

	sni, err := ExtractSNI(rawClientHello)
	if err != nil {
		t.Fatalf("extractSNI failed: %v", err)
	}
	if sni != "example.com" {
		t.Errorf("Expected example.com, got %s", sni)
	}
}